    public static void DrawText(Span<uint> pixels, int width, int height, int x, int y, string text, uint foreground, uint? background = null)
    {
        ArgumentNullException.ThrowIfNull(text);

        var cursorX = x;
        var cursorY = y;
        foreach (var ch in text)
        {
            if (ch == '\r')
            {
                continue;
            }

            if (ch == '\n')
            {
                cursorX = x;
                cursorY += CellHeight;
                continue;
            }

            DrawGlyph(pixels, width, height, cursorX, cursorY, ch, foreground, background);
            cursorX += CellWidth;
        }
    }

    private static void DrawGlyph(Span<uint> pixels, int width, int height, int x, int y, char ch, uint foreground, uint? background)
    {
        var glyph = GetGlyph(ch);
        for (var yy = 0; yy < CellHeight; yy++)
        {
            var py = y + yy;
            if (py < 0 || py >= height)
            {
                continue;
            }

            for (var xx = 0; xx < CellWidth; xx++)
            {
                var px = x + xx;
                if (px < 0 || px >= width)
                {
                    continue;
                }

                var isGlyphPixel = yy >= 2 &&
                    yy < 9 &&
                    xx >= 1 &&
                    xx < 6 &&
                    glyph[yy - 2][xx - 1] != ' ';

                if (isGlyphPixel)
                {
                    pixels[(py * width) + px] = foreground;
                }
                else if (background.HasValue)
                {
                    pixels[(py * width) + px] = background.Value;
                }
            }
        }
    }

    private static string[] GetGlyph(char ch)
    {
        if (Glyphs.TryGetValue(ch, out var glyph))
        {
            return glyph;
        }

        var upper = char.ToUpperInvariant(ch);
        if (Glyphs.TryGetValue(upper, out glyph))
        {
            return glyph;
        }

        return ["#####", "#   #", "# # #", "# # #", "#   #", "#####", "     "];
    }
